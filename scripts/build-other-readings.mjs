/**
 * Writes src/server/database/seed/other-readings.tsv: for each character, the
 * standard readings besides its main one (`vocab_items.pinyin`).
 *
 * WHY: a reading card shows a character alone, and a character with several
 * readings is correctly answered by any of them — 觉 is jué in 觉得 and jiào in
 * 睡觉, 长 is cháng and zhǎng. One reading per row marked the other one wrong.
 *
 * Sources, unioned:
 *   - dictionary.txt's `pinyin` list (makemeahanzi; rarely more than one)
 *   - Reading and Writing Chinese's head readings (books/extracted/
 *     rwc-entries-v2.jsonl, gitignored; see scripts/extract-rwc.mjs), which
 *     list a character's readings together ("DE, DÌ") — 206 characters have
 *     more than one
 *
 * Minus the main reading, anything that is not one valid syllable (RWC writes
 * "zháo, zháole"), and DENY: readings an override replaced because they are
 * wrong for the character on its own, not merely secondary.
 *
 * Run:  node scripts/build-other-readings.mjs
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import process from "node:process";

const REPO = process.cwd();
const SEED = join(REPO, "src/server/database/seed");
const RWC = join(REPO, "books/extracted/rwc-entries-v2.jsonl");

const DENY = {
  呢: ["né"], // makemeahanzi's; the particle is ne and the cloth is ní
  子: ["zi"], // the neutral-tone suffix of 桌子, not the character alone
  卓: ["zhuō"], // older reading; standard zhuó
};

if (!existsSync(RWC)) {
  throw new Error(`${RWC} is missing; run scripts/extract-rwc.mjs first`);
}

const nfc = (s) => s.normalize("NFC").trim().toLowerCase();
const toneless = (s) =>
  s
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase();
const toneMarks = (s) =>
  (s.normalize("NFD").match(/[\u0300\u0301\u030c\u0304]/g) ?? []).length;

const dictionary = readFileSync(join(SEED, "dictionary.txt"), "utf8")
  .split("\n")
  .filter((line) => line.trim())
  .map((line) => JSON.parse(line));

// One Mandarin syllable: an optional initial and a final. Checked on the
// toneless form (ü folds to u). Rejects run-ons like RWC's "zháole".
const SYLLABLE =
  /^(?:(?:zh|ch|sh|[bpmfdtnlgkhjqxrzcsyw])?(?:iang|iong|uang|ueng|ang|eng|ing|ong|ian|iao|uai|uan|ai|ei|ao|ou|an|en|er|ia|ie|iu|in|ua|uo|ui|un|ue|a|o|e|i|u)|ng|hng|hm|m|n)$/;
const isSyllable = (p) => SYLLABLE.test(toneless(p)) && toneMarks(p) <= 1;

const disabled = new Set(
  readFileSync(join(SEED, "vocab-classification.tsv"), "utf8")
    .split("\n")
    .map((line) => line.split("\t"))
    .filter((cols) => cols[2] === "disabled")
    .map((cols) => cols[0]),
);

const overridePinyin = new Map(
  readFileSync(join(SEED, "vocab-overrides.tsv"), "utf8")
    .split("\n")
    .filter((line) => line.trim() && !line.startsWith("#"))
    .map((line) => line.split("\t"))
    .filter((cols) => cols[1])
    .map((cols) => [cols[0], nfc(cols[1])]),
);

const rwcReadings = new Map();
for (const line of readFileSync(RWC, "utf8").split("\n")) {
  if (!line.trim()) continue;
  const entry = JSON.parse(line);
  if (!entry.pinyin || Array.from(entry.glyph).length !== 1) continue;
  const list = rwcReadings.get(entry.glyph) ?? [];
  for (const p of entry.pinyin.split(/[,;]/)) if (p.trim()) list.push(nfc(p));
  rwcReadings.set(entry.glyph, list);
}

const rows = [];
for (const entry of dictionary) {
  const glyph = entry.character;
  if (disabled.has(glyph)) continue;
  const main =
    overridePinyin.get(glyph) ??
    (entry.pinyin?.[0] ? nfc(entry.pinyin[0]) : "");
  if (!main) continue;
  const others = [];
  for (const p of [
    ...(entry.pinyin ?? []).map(nfc),
    ...(rwcReadings.get(glyph) ?? []),
  ]) {
    if (p === main || others.includes(p)) continue;
    if (!isSyllable(p) || DENY[glyph]?.includes(p)) continue;
    others.push(p);
  }
  if (others.length) rows.push(`${glyph}\t${others.join(",")}`);
}

writeFileSync(
  join(SEED, "other-readings.tsv"),
  `# Generated by scripts/build-other-readings.mjs — do not edit by hand.\n` +
    `# glyph\tother readings, comma-separated (the main one is vocab_items.pinyin)\n` +
    `${rows.join("\n")}\n`,
);
console.log(`Wrote ${rows.length} characters with other readings.`);
